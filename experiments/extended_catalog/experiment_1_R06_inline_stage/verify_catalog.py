#!/usr/bin/env python3
"""
verify_catalog.py — standalone verification for R06 — Inline Stage.

Generated by reset_total.py on 2026-07-17 14:11:49 UTC. Self-contained: it reads only the files
in this folder and depends on nothing outside it.

    python verify_catalog.py

The logical instruction count runs anywhere. The other three indicators need a
reachable Docker daemon; without one the script reports what it can and says
what it skipped, rather than failing.

    pip install dockerfile-parse
"""

import io
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BEFORE_DF = HERE / "Dockerfile.before"
AFTER_DFS = [HERE / p for p in ['Dockerfile.after']]
CONTEXT_BEFORE = HERE / "."
CONTEXT_AFTER = HERE / "."
# Global, unified maintainability filter — identical in every verification
# script. It is the full maintainability rule set of the Hadolint wiki:
# reproducibility (16), structural correctness (15), usage & notation (12),
# metadata (1), shell/ShellCheck (2), logs (1).
HADOLINT_FILTER = [
    # Reproducibility
    "DL3005", "DL3006", "DL3007", "DL3008", "DL3013", "DL3016", "DL3017",
    "DL3018", "DL3028", "DL3031", "DL3033", "DL3035", "DL3037", "DL3039",
    "DL3041", "DL3062",
    # Structural correctness
    "DL3000", "DL3003", "DL3011", "DL3012", "DL3021", "DL3022", "DL3023",
    "DL3024", "DL3043", "DL3044", "DL3045", "DL3061", "DL3063", "DL4003",
    "DL4004",
    # Usage and notation
    "DL3001", "DL3010", "DL3014", "DL3025", "DL3027", "DL3029", "DL3030",
    "DL3034", "DL3038", "DL4001", "DL4005", "DL4006",
    # Metadata
    "DL4000",
    # Shell (ShellCheck)
    "SC2046", "SC2086",
    # Logs
    "DL3047",
]
REPORTED = {'delta_instr': -3, 'delta_size': 116, 'delta_cves': 0, 'delta_warnings': 0}
TAG = "verify-exp-r06"


def instructions(path):
    """Logical instructions, COMMENT excluded. An instruction spanning several
    physical lines through backslash continuations counts as one."""
    from dockerfile_parse import DockerfileParser
    raw = path.read_bytes().replace(b"\r\n", b"\n")
    dfp = DockerfileParser(fileobj=io.BytesIO(raw))
    return [e["instruction"] for e in dfp.structure if e["instruction"] != "COMMENT"]


def sh(cmd, stdin=None):
    return subprocess.run(cmd, input=stdin, stdout=subprocess.PIPE,
                          stderr=subprocess.DEVNULL, check=False).stdout


def docker_up():
    return subprocess.run(["docker", "info"], stdout=subprocess.DEVNULL,
                          stderr=subprocess.DEVNULL, check=False).returncode == 0


def unique_cves(report):
    ids = set()
    for result in report.get("Results") or []:
        for vuln in result.get("Vulnerabilities") or []:
            if vuln.get("VulnerabilityID"):
                ids.add(vuln["VulnerabilityID"])
    return len(ids)


def warnings_total(dockerfile):
    """Warnings total: Hadolint findings within the maintainability rule set."""
    raw = sh(["docker", "run", "--rm", "-i", "hadolint/hadolint",
              "hadolint", "--format", "json", "-"], stdin=dockerfile.read_bytes())
    codes = [i.get("code") for i in json.loads(raw.decode() or "[]")]
    return sum(1 for c in codes if c in HADOLINT_FILTER)


def row(label, before, after, delta):
    return f"| {label:<34} | {before:>14} | {after:>14} | {delta:>+13} |"


def main():
    bar = "+" + "-" * 36 + "+" + "-" * 16 + "+" + "-" * 16 + "+" + "-" * 15 + "+"
    print()
    print("=" * 86)
    print(f"  R06 — Inline Stage")
    print("  Standalone verification — measures the files in this folder")
    print("=" * 86)

    before = instructions(BEFORE_DF)
    after = []
    for path in AFTER_DFS:
        after += instructions(path)
    d_instr = len(after) - len(before)

    measured = {"delta_instr": d_instr}
    have_docker = docker_up()

    if have_docker:
        print("\n  Building both states with --no-cache. This takes a minute.")
        sizes, cves, warns = {}, {}, {}
        for label, dockerfile, ctx in (("before", BEFORE_DF, CONTEXT_BEFORE),
                                       ("after", AFTER_DFS[0], CONTEXT_AFTER)):
            build = subprocess.run(
                ["docker", "build", "--no-cache", "-f", str(dockerfile),
                 "-t", f"{TAG}:{label}", str(ctx)],
                stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, check=False)
            if build.returncode != 0:
                tail = build.stderr.decode(errors="replace").strip().splitlines()
                print(f"    {label}: BUILD FAILED — {tail[-1][:70] if tail else ''}")
                have_docker = False
                break
            sizes[label] = int(sh(["docker", "image", "inspect", f"{TAG}:{label}",
                                   "--format", "{{.Size}}"]).decode().strip())
            report = sh(["docker", "run", "--rm",
                         "-v", "/var/run/docker.sock:/var/run/docker.sock",
                         "aquasec/trivy", "image", "--quiet", "--format", "json",
                         f"{TAG}:{label}"])
            cves[label] = unique_cves(json.loads(report.decode() or "{}"))
            warns[label] = warnings_total(dockerfile)

        if have_docker:
            measured.update(delta_size=sizes["after"] - sizes["before"],
                            delta_cves=cves["after"] - cves["before"],
                            delta_warnings=warns["after"] - warns["before"])

    print("\n" + bar)
    print(f"| {'Indicator':<34} | {'Before':>14} | {'After':>14} | {'Delta':>13} |")
    print(bar)
    if "delta_size" in measured:
        print(row("Image size (bytes)", f"{sizes['before']:,}",
                  f"{sizes['after']:,}", measured["delta_size"]))
        print(row("CVEs (unique)", cves["before"], cves["after"], measured["delta_cves"]))
        print(row("Hadolint warnings (total)", warns["before"], warns["after"],
                  measured["delta_warnings"]))
    else:
        for label in ("Image size (bytes)", "CVEs (unique)", "Hadolint warnings (total)"):
            print(f"| {label:<34} | {'skipped':>14} | {'skipped':>14} | {'—':>13} |")
    print(row("Logical instructions", len(before), len(after), d_instr))
    print(bar)

    print(f"\n  before : {' '.join(before)}")
    print(f"  after  : {' '.join(after)}")
    if len(AFTER_DFS) > 1:
        print(f"  (after spans {len(AFTER_DFS)} files: "
              f"{', '.join(p.name for p in AFTER_DFS)})")

    if not have_docker:
        print("\n  Docker unreachable, so size, CVEs and warnings were skipped.")
        print("  The logical instruction count needs no daemon and is shown above.")

    print("\n  Against the values reported in the dissertation")
    drift = False
    for key, expected in REPORTED.items():
        if expected is None or key not in measured:
            continue
        got = measured[key]
        if got != expected:
            drift = True
        print(f"    {'OK  ' if got == expected else 'DIFF'} {key:<16} "
              f"reported {expected:+,}   measured {got:+,}")
    if drift:
        print("\n  A difference here is not necessarily an error. Image sizes and CVE")
        print("  counts depend on the base image and on the Trivy vulnerability")
        print("  database at the time of measurement. The digests and tool versions")
        print("  behind the reported values are in reset_total/out/environment.json.")
    print()


if __name__ == "__main__":
    sys.exit(main())
